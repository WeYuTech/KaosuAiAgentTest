-- AI 專用資料表。僅供部署審核，本次開發不會對正式資料庫執行。
-- 時間 OCCURRED_AT 依 MES 資料庫當地時間（台灣），其餘 *_UTC 使用 UTC。
-- 需於隔離 SQL Server 資料庫驗證後，以具 DDL 權限的部署身分執行。
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.ZZ_AI_AGENT_OPERATION_OPERATION', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ZZ_AI_AGENT_OPERATION_OPERATION (
        OPERATION_ID uniqueidentifier NOT NULL PRIMARY KEY,
        OCCURRED_AT datetime2(7) NOT NULL,
        MODULE nvarchar(20) NOT NULL,
        ACTOR_ID nvarchar(50) NOT NULL,
        ACTION nvarchar(80) NOT NULL,
        REQUEST_HASH char(64) NOT NULL,
        RESULT nvarchar(32) NOT NULL,
        RESULT_JSON nvarchar(max) NOT NULL,
        CONSTRAINT CK_AI_OPERATION_RESULT_JSON CHECK (ISJSON(RESULT_JSON)=1),
        CONSTRAINT CK_AI_OPERATION_MODULE CHECK (MODULE IN (N'schedule',N'report',N'mold'))
    );
    CREATE INDEX IX_AI_OPERATION_TIME ON dbo.ZZ_AI_AGENT_OPERATION_OPERATION(OCCURRED_AT DESC, ACTOR_ID);
END;

IF OBJECT_ID(N'dbo.ZZ_AI_AGENT_OPERATION_CHANGE', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ZZ_AI_AGENT_OPERATION_CHANGE (
        OPERATION_ID uniqueidentifier NOT NULL,
        SEQ int NOT NULL,
        TABLE_NAME nvarchar(128) NOT NULL,
        ROW_KEY nvarchar(255) NOT NULL,
        COLUMN_NAME nvarchar(128) NOT NULL,
        BEFORE_JSON nvarchar(max) NOT NULL,
        AFTER_JSON nvarchar(max) NOT NULL,
        CONSTRAINT PK_AI_CHANGE PRIMARY KEY(OPERATION_ID,SEQ),
        CONSTRAINT FK_AI_CHANGE_OPERATION FOREIGN KEY(OPERATION_ID)
            REFERENCES dbo.ZZ_AI_AGENT_OPERATION_OPERATION(OPERATION_ID)
    );
END;

-- 後續正式模式的確認卡、回饋與核准知識；本機模擬使用 SQLite，不能混充正式紀錄。
IF OBJECT_ID(N'dbo.ZZ_AI_AGENT_OPERATION_PROPOSAL', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ZZ_AI_AGENT_OPERATION_PROPOSAL (
        PROPOSAL_ID uniqueidentifier NOT NULL PRIMARY KEY,
        ACTOR_ID nvarchar(50) NOT NULL,
        MODULE nvarchar(20) NOT NULL,
        ACTION nvarchar(80) NOT NULL,
        VERSION_HASH char(64) NOT NULL,
        PAYLOAD_JSON nvarchar(max) NOT NULL,
        STATUS nvarchar(32) NOT NULL,
        CREATED_UTC datetime2(7) NOT NULL DEFAULT SYSUTCDATETIME(),
        EXPIRES_UTC datetime2(7) NOT NULL,
        CONFIRMED_UTC datetime2(7) NULL,
        OPERATION_ID uniqueidentifier NULL,
        CONSTRAINT CK_AI_PROPOSAL_JSON CHECK(ISJSON(PAYLOAD_JSON)=1)
    );
END;

IF OBJECT_ID(N'dbo.ZZ_AI_AGENT_OPERATION_FEEDBACK', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ZZ_AI_AGENT_OPERATION_FEEDBACK (
        FEEDBACK_ID uniqueidentifier NOT NULL PRIMARY KEY,
        OPERATION_ID uniqueidentifier NULL,
        ACTOR_ID nvarchar(50) NOT NULL,
        CREATED_UTC datetime2(7) NOT NULL DEFAULT SYSUTCDATETIME(),
        CONTENT nvarchar(4000) NOT NULL,
        STATUS nvarchar(32) NOT NULL DEFAULT N'pending',
        REVIEWED_BY nvarchar(50) NULL,
        REVIEWED_UTC datetime2(7) NULL
    );
END;

IF OBJECT_ID(N'dbo.ZZ_AI_AGENT_OPERATION_KNOWLEDGE', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ZZ_AI_AGENT_OPERATION_KNOWLEDGE (
        KNOWLEDGE_ID uniqueidentifier NOT NULL,
        VERSION int NOT NULL,
        MODULE nvarchar(20) NOT NULL,
        TITLE nvarchar(255) NOT NULL,
        CONTENT nvarchar(max) NOT NULL,
        SOURCE_REFERENCE nvarchar(1000) NOT NULL,
        SOURCE_HASH char(64) NOT NULL,
        STATUS nvarchar(32) NOT NULL DEFAULT N'draft',
        APPROVED_BY nvarchar(50) NULL,
        APPROVED_UTC datetime2(7) NULL,
        CONSTRAINT PK_AI_KNOWLEDGE PRIMARY KEY(KNOWLEDGE_ID,VERSION)
    );
END;

IF OBJECT_ID(N'dbo.ZZ_AI_AGENT_OPERATION_BUDGET', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ZZ_AI_AGENT_OPERATION_BUDGET (
        REQUEST_ID uniqueidentifier NOT NULL PRIMARY KEY,
        CREATED_UTC datetime2(7) NOT NULL DEFAULT SYSUTCDATETIME(),
        MODEL nvarchar(100) NOT NULL,
        RESERVATION_USD decimal(18,8) NOT NULL,
        ACTUAL_USD decimal(18,8) NULL,
        STATUS nvarchar(32) NOT NULL,
        INPUT_TOKENS bigint NULL,
        OUTPUT_TOKENS bigint NULL,
        CONSTRAINT CK_AI_BUDGET_AMOUNT CHECK(RESERVATION_USD>=0 AND (ACTUAL_USD IS NULL OR ACTUAL_USD>=0))
    );
END;
COMMIT TRANSACTION;
